#!/usr/bin/env python3
"""Regenerates core/overlay/icon.inc: the project icon (assets/branding/icon-64.png) as premultiplied RGBA words, so the
in-game menu can draw it without loading a file. Needs Pillow (pip install pillow); run it again only when the icon
changes."""

import pathlib
import sys

from PIL import Image

root = pathlib.Path(__file__).resolve().parent.parent
source = root / "assets" / "branding" / "icon-64.png"
target = root / "core" / "overlay" / "icon.inc"

image = Image.open(source).convert("RGBA")
if image.size != (64, 64):
    sys.exit(f"{source} must be 64x64, it is {image.size}")

words = []
data = image.tobytes()
for i in range(0, len(data), 4):
    r, g, b, a = data[i : i + 4]
    r, g, b = ((c * a + 127) // 255 for c in (r, g, b))
    words.append(r | (g << 8) | (b << 16) | (a << 24))

lines = [
    "// Generated by scripts/gen_overlay_icon.py from assets/branding/icon-64.png. Do not edit.",
    "// 64x64 pixels, premultiplied RGBA packed as r | g << 8 | b << 16 | a << 24, row by row from the top.",
]
for i in range(0, len(words), 8):
    lines.append(", ".join(f"0x{w:08X}u" for w in words[i : i + 8]) + ",")
target.write_text("\n".join(lines) + "\n", encoding="ascii")
print(f"wrote {target} ({len(words)} pixels)")
