#!/usr/bin/env python3
"""Makes host/shadow_zones.inc: which zone of which map each of the game's textures belongs to.

Reads the [hashes] of a texture pack ini that sorts its images by zone (areas/hunting/<map>/<zone>, areas/pokke/<place>) and
keeps only the identification hashes and the folder names: no image and nothing else from the pack.

    python games/mhfu/tools/make_shadow_zones.py games/mhfu/host/shadow_zones.inc textures_FU_EU.ini textures_FU_US.ini
"""
import re
import sys

LINE = re.compile(r"^[0-9a-fA-F]{16}([0-9a-fA-F]{8})\s*=\s*(areas/\S+)/[^/\s]+$")


def zone_of(folder):
    parts = folder.split("/")
    if parts[1] == "hunting":
        return folder if len(parts) == 4 and (parts[3].startswith("area") or parts[3] == "base") else None
    return folder if parts[1] == "pokke" and len(parts) == 3 else None


def main():
    output, *inis = sys.argv[1:]
    zones = {}  # hash -> zone; a texture in two zones says nothing and is dropped
    shared = set()
    for ini in inis:
        with open(ini, encoding="utf-8", errors="replace") as f:
            for line in f:
                match = LINE.match(line.strip())
                zone = zone_of(match[2]) if match else None
                if zone is None:
                    continue
                key = match[1].lower()
                if zones.get(key, zone) != zone:
                    shared.add(key)
                zones[key] = zone
    for key in shared:
        del zones[key]
    names = sorted(set(zones.values()))
    index = {name: i for i, name in enumerate(names)}
    with open(output, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by games/mhfu/tools/make_shadow_zones.py: identification hashes of the game's textures and their zones.\n#pragma once\n\n")
        f.write("#include <cstdint>\n\nstruct ShadowZoneTexture {\n    std::uint32_t hash;\n    int zone;\n};\n\n")
        f.write("inline constexpr const char *kShadowZoneNames[] = {\n")
        for name in names:
            f.write(f'    "{name}",\n')
        f.write("};\n\ninline constexpr ShadowZoneTexture kShadowZoneTextures[] = {\n")
        for key in sorted(zones):
            f.write(f"    {{0x{key}u, {index[zones[key]]}}},\n")
        f.write("};\n")
    print(f"{len(zones)} textures in {len(names)} zones, {len(shared)} shared by zones and left out")


main()
